-- Queen Burger database setup for Supabase
-- Run this entire script in Supabase > SQL Editor.
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  customer_phone text not null,
  customer_address text not null,
  notes text,
  items jsonb not null,
  total_iqd integer not null check (total_iqd >= 0),
  status text not null default 'new'
    check (status in ('new','accepted','preparing','out_for_delivery','delivered','cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.orders enable row level security;
alter table public.admin_users enable row level security;

-- Customers may submit an order without logging in.
drop policy if exists "public can create orders" on public.orders;
create policy "public can create orders" on public.orders
for insert to anon, authenticated
with check (
  customer_name <> '' and customer_phone <> '' and customer_address <> ''
  and total_iqd >= 0 and status = 'new'
);

-- Only a signed-in account explicitly listed in admin_users can read/update orders.
drop policy if exists "admins can read orders" on public.orders;
create policy "admins can read orders" on public.orders
for select to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "admins can update orders" on public.orders;
create policy "admins can update orders" on public.orders
for update to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

-- Admins can check their own membership. No public insert policy is provided.
drop policy if exists "admins can read own membership" on public.admin_users;
create policy "admins can read own membership" on public.admin_users
for select to authenticated
using (user_id = auth.uid());

